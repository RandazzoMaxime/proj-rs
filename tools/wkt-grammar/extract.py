#!/usr/bin/env python3
"""Extract the bison tables of PROJ's WKT1 and WKT2 grammars into Rust modules.

Usage: tools/wkt-grammar/extract.py <PROJ source dir> [<output dir>]

Reads src/wkt{1,2}_generated_parser.{c,h} (bison 3.5.1, yacc.c skeleton) and the
tokens[] tables of src/wkt{1,2}_parser.cpp, and writes wkt1_tables.rs and
wkt2_tables.rs (default output: src/iso19111/wkt_grammar/ of this repository).
"""

import os
import re
import sys

PROJ_VERSION = "9.9.0"

TABLES = [
    "yytranslate",
    "yypact",
    "yydefact",
    "yypgoto",
    "yydefgoto",
    "yytable",
    "yycheck",
    "yyr1",
    "yyr2",
]

DEFINES = ["YYFINAL", "YYLAST", "YYNTOKENS", "YYUNDEFTOK", "YYMAXUTOK", "YYPACT_NINF", "YYTABLE_NINF"]


def fail(message):
    sys.exit("extract.py: " + message)


def read(path):
    with open(path, encoding="utf-8") as handle:
        return handle.read()


def define(source, name):
    match = re.search(r"^#define %s\s+\(?(-?\d+)\)?\s*$" % name, source, re.M)
    if not match:
        fail("no #define %s" % name)
    return int(match.group(1))


def int_table(source, name):
    match = re.search(r"static const yytype_\w+ %s\[\] =\s*\{([^}]*)\};" % name, source)
    if not match:
        fail("no table %s" % name)
    values = [int(value) for value in match.group(1).replace("\n", " ").split(",") if value.strip()]
    for value in values:
        if not -32768 <= value <= 32767:
            fail("%s holds %d, outside i16" % (name, value))
    return values


def c_string(literal):
    """The bytes of a C string literal body, for the escapes bison writes in yytname."""
    out = []
    index = 0
    while index < len(literal):
        char = literal[index]
        if char == "\\":
            index += 1
            escaped = literal[index]
            if escaped in "\"'\\?":
                out.append(escaped)
            elif escaped == "n":
                out.append("\n")
            elif escaped == "t":
                out.append("\t")
            else:
                fail("unsupported escape \\%s in yytname" % escaped)
        else:
            out.append(char)
        index += 1
    return "".join(out)


def tname(source, ntokens):
    match = re.search(r"static const char \*const yytname\[\] =\s*\{(.*?)\};", source, re.S)
    if not match:
        fail("no yytname")
    names = [c_string(body) for body in re.findall(r'"((?:[^"\\]|\\.)*)"', match.group(1))]
    if len(names) < ntokens:
        fail("yytname has %d names for %d tokens" % (len(names), ntokens))
    return names


def token_enum(header):
    match = re.search(r"enum yytokentype\s*\{(.*?)\};", header, re.S)
    if not match:
        fail("no enum yytokentype")
    return {name: int(value) for name, value in re.findall(r"(\w+)\s*=\s*(\d+)", match.group(1))}


def lexer_keywords(parser_cpp, tokens):
    match = re.search(r"static const \w+ tokens\[\] = \{(.*?)\};", parser_cpp, re.S)
    if not match:
        fail("no tokens[] in the lexer")
    body = re.sub(r"//[^\n]*", "", match.group(1))
    keywords = []
    for name in re.findall(r"PAIR\((\w+)\)", body):
        if "T_" + name not in tokens:
            fail("lexer keyword %s has no token" % name)
        keywords.append((name, tokens["T_" + name]))
    return keywords


def rust_array(name, doc, values, kind="i16"):
    lines = ["/// %s" % doc, "pub(super) static %s: [%s; %d] = [" % (name, kind, len(values))]
    row = "   "
    for value in values:
        cell = " %s," % value
        if len(row) + len(cell) > 99:
            lines.append(row)
            row = "   "
        row += cell
    lines.append(row)
    lines.append("];")
    return "\n".join(lines)


def rust_string(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def generate(src, grammar, extra_tokens):
    source = read(os.path.join(src, "src", "%s_generated_parser.c" % grammar))
    header = read(os.path.join(src, "src", "%s_generated_parser.h" % grammar))
    lexer = read(os.path.join(src, "src", "%s_parser.cpp" % grammar))
    if '#define YYBISON_VERSION "3.5.1"' not in source or '"yacc.c"' not in source:
        fail("%s: not a bison 3.5.1 yacc.c parser" % grammar)
    if not re.search(r"#define yytable_value_is_error\(Yyn\) \\\s*0\s*\n", source):
        fail("%s: yytable_value_is_error is not 0; the driver assumes it is" % grammar)
    defines = {name: define(source, name) for name in DEFINES}
    tables = {name: int_table(source, name) for name in TABLES}
    if len(tables["yytranslate"]) != defines["YYMAXUTOK"] + 1:
        fail("%s: yytranslate size" % grammar)
    names = tname(source, defines["YYNTOKENS"])[: defines["YYNTOKENS"]]
    tokens = token_enum(header)
    keywords = lexer_keywords(lexer, tokens)

    out = []
    out.append(
        "// @generated by tools/wkt-grammar/extract.py from PROJ %s src/%s_generated_parser.c "
        "(bison 3.5.1); do not edit." % (PROJ_VERSION, grammar)
    )
    out.append(
        "// YYTABLE_NINF = %d; yytable_value_is_error is 0, so the driver never reads it."
        % defines["YYTABLE_NINF"]
    )
    out.append("")
    out.append("use super::Tables;")
    out.append("")
    for name, value in extra_tokens(tokens):
        out.append("/// `%s` of `%s_generated_parser.h`." % (name, grammar))
        out.append("pub(super) const %s: i32 = %d;" % (name, value))
    out.append("")
    out.append("/// `tokens[]` of `%s_parser.cpp`, in its order." % grammar)
    out.append("pub(super) static KEYWORDS: [(&str, i32); %d] = [" % len(keywords))
    for name, value in keywords:
        out.append("    (%s, %d)," % (rust_string(name), value))
    out.append("];")
    out.append("")
    out.append("/// `yytname` of the terminal symbols.")
    out.append("static YYTNAME: [&str; %d] = [" % len(names))
    for name in names:
        out.append("    %s," % rust_string(name))
    out.append("];")
    out.append("")
    statics = []
    for name in TABLES:
        statics.append(rust_array(name.upper(), "`%s`." % name, tables[name]))
    out.append("\n\n".join(statics))
    out.append("")
    out.append("/// The tables of `%s_generated_parser.c`." % grammar)
    out.append("pub(super) static TABLES: Tables = Tables {")
    out.append("    yyfinal: %d," % defines["YYFINAL"])
    out.append("    yylast: %d," % defines["YYLAST"])
    out.append("    yyntokens: %d," % defines["YYNTOKENS"])
    out.append("    yyundeftok: %d," % defines["YYUNDEFTOK"])
    out.append("    yymaxutok: %d," % defines["YYMAXUTOK"])
    out.append("    yypact_ninf: %d," % defines["YYPACT_NINF"])
    out.append("    yytname: &YYTNAME,")
    for name in TABLES:
        out.append("    %s: &%s," % (name, name.upper()))
    out.append("};")
    return "\n".join(out) + "\n"


def wkt1_tokens(tokens):
    return [(name, tokens[name]) for name in ("T_STRING", "T_NUMBER", "T_IDENTIFIER")]


def wkt2_tokens(tokens):
    return [(name, tokens[name]) for name in ("T_STRING", "T_UNSIGNED_INTEGER_DIFFERENT_ONE_TWO_THREE")]


def main():
    if len(sys.argv) not in (2, 3):
        fail("usage: extract.py <PROJ source dir> [<output dir>]")
    src = sys.argv[1]
    here = os.path.dirname(os.path.abspath(__file__))
    default_out = os.path.join(here, "..", "..", "src", "iso19111", "wkt_grammar")
    out_dir = sys.argv[2] if len(sys.argv) == 3 else default_out
    for grammar, extra in (("wkt1", wkt1_tokens), ("wkt2", wkt2_tokens)):
        path = os.path.join(out_dir, "%s_tables.rs" % grammar)
        with open(path, "w", encoding="utf-8") as handle:
            handle.write(generate(src, grammar, extra))
        print("wrote", os.path.normpath(path))


if __name__ == "__main__":
    main()
