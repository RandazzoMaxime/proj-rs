//! C API of proj-rs: the `proj.h` of PROJ 9.9.0 on the proj-rs engine.
//!
//! Every exported function has the name, the signature and the semantics of its `proj.h`
//! twin; `include/proj.h` is the header of PROJ 9.9.0, byte for byte. A function the port
//! cannot honour returns the error of PROJ (`NULL` or 0, with `proj_errno` set), never a
//! wrong result, and no panic crosses the boundary: each entry point runs under
//! [`util::guard`].
//!
//! The exported functions take raw pointers in a *safe* signature: the C contract (a valid
//! pointer or `NULL`) is checked and relied on in `util` only, where each `unsafe` block says
//! why it holds. This crate is a C ABI, not a Rust API: `docs/API-v1.md` § C.
#![allow(
    missing_docs,
    reason = "each function is documented by its twin in proj.h, which defines its contract"
)]
#![allow(
    clippy::as_conversions,
    clippy::cast_possible_truncation,
    clippy::cast_sign_loss,
    clippy::cast_possible_wrap,
    clippy::too_many_arguments,
    clippy::not_unsafe_ptr_arg_deref,
    reason = "the C ABI fixes the integer and pointer types of every signature"
)]
#![allow(
    unreachable_pub,
    reason = "the exported functions are `pub` for the C symbol table, not for Rust callers"
)]
#![allow(
    missing_debug_implementations,
    clippy::unreadable_literal,
    clippy::missing_safety_doc,
    clippy::upper_case_acronyms,
    clippy::identity_op,
    clippy::unnecessary_operation,
    reason = "ffi.rs is generated by bindgen from proj.h: the names and the layouts are the header's"
)]
#![allow(
    clippy::wildcard_imports,
    reason = "the names of proj.h are imported together from the generated `ffi` module"
)]
#![allow(
    non_camel_case_types,
    non_snake_case,
    non_upper_case_globals,
    reason = "the names are those of proj.h"
)]

