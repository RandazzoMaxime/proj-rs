#!/usr/bin/env python3
"""Write src/lists_data.rs: the static tables of proj_list_* from a PROJ 9.9.0 source tree.

usage: gen_lists.py PROJ_SRC OUTPUT       (PROJ_SRC holds src/ellps.cpp, src/units.cpp...)

The tables are PROJ's own: the projections of `pj_list.h` with the description each projection
file gives, `ellps.cpp`, `units.cpp` (linear and angular) and `datums.cpp` (prime meridians).
"""
import glob
import math
import os
import re
import sys


def c_string(text: str) -> str:
    """The value of the adjacent string literals in `text`, C escapes resolved."""
    parts = re.findall(r'"((?:[^"\\]|\\.)*)"', text)
    joined = "".join(parts)
    return bytes(joined, "utf-8").decode("unicode_escape")


def rust(text: str) -> str:
    out = text.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n").replace("\t", "\\t")
    return f'"{out}"'


def main() -> int:
    root, output = sys.argv[1:3]
    src = os.path.join(root, "src")
    listing = open(os.path.join(src, "pj_list.h"), encoding="utf-8").read()
    base = dict(re.findall(r'PROJ_HEAD\((\w+),\s*"((?:[^"\\]|\\.)*)"\)', listing))
    order = re.findall(r"PROJ_HEAD\((\w+),", listing)
    full = {}
    literal = r'"(?:[^"\\]|\\.)*"'
    for path in sorted(glob.glob(os.path.join(src, "**", "*.cpp"), recursive=True)):
        text = open(path, encoding="utf-8").read()
        # A description may end with a string macro: `#define LINE2 "..."` in sconics.cpp.
        macros = dict(re.findall(r'#define\s+(\w+)\s+((?:' + literal + r'\s*)+)\n', text))
        head_re = r'PROJ_HEAD\((\w+),\s*(' + literal + r')\)\s*((?:(?:' + literal + r'|\w+)\s*)*);'
        for match in re.finditer(head_re, text):
            ident, head, tail = match.groups()
            pieces = re.findall(literal + r'|\w+', tail)
            tail = "".join(piece if piece.startswith('"') else macros.get(piece, "") for piece in pieces)
            full[ident] = c_string(head + tail)
    lines = [
        "//! The tables of `proj_list_*`, from PROJ 9.9.0. Generated by `capi/tools/gen_lists.py`.",
        "",
        "/// `pj_list.h`: projection id and description.",
        "pub(crate) const OPERATIONS: &[(&str, &str)] = &[",
    ]
    for ident in order:
        lines.append(f"    ({rust(ident)}, {rust(full.get(ident, c_string(chr(34) + base[ident] + chr(34))))}),")
    lines += ["];", "", "/// `ellps.cpp`: id, major, ell, name.", "pub(crate) const ELLIPSOIDS: &[(&str, &str, &str, &str)] = &["]
    ell = open(os.path.join(src, "ellps.cpp"), encoding="utf-8").read()
    ell = ell[ell.index("pj_ellps[]") :]
    for row in re.finditer(r'\{\s*"([^"]*)",\s*"([^"]*)",\s*"([^"]*)",\s*"((?:[^"\\]|\\.)*)"\s*\}', ell):
        lines.append("    (" + ", ".join(rust(g) for g in row.groups()) + "),")
    lines += ["];", "", "/// `units.cpp`: id, to_meter, name, factor."]

    def units(name: str, array: str) -> None:
        text = open(os.path.join(src, "units.cpp"), encoding="utf-8").read()
        text = text[text.index(array) :]
        text = text[: text.index("{nullptr")]
        lines.append(f"pub(crate) const {name}: &[(&str, &str, &str, f64)] = &[")
        for row in re.finditer(r'\{\s*"([^"]*)",\s*"([^"]*)",\s*"((?:[^"\\]|\\.)*)",\s*([^}]*?)\}', text):
            ident, to, label, factor = row.groups()
            factor = factor.replace("DEG_TO_RAD", repr(math.pi / 180)).replace("GRAD_TO_RAD", repr(math.pi / 200))
            lines.append(f"    ({rust(ident)}, {rust(to)}, {rust(label)}, {float(eval(factor.strip()))!r}),")
        lines.append("];")

    units("LINEAR_UNITS", "pj_units[]")
    lines.append("")
    units("ANGULAR_UNITS", "pj_angular_units[]")
    lines += ["", "/// `datums.cpp`: prime meridian id and definition.", "pub(crate) const PRIME_MERIDIANS: &[(&str, &str)] = &["]
    datums = open(os.path.join(src, "datums.cpp"), encoding="utf-8").read()
    datums = datums[datums.index("pj_prime_meridians[]") :]
    datums = datums[: datums.index("{nullptr")]
    for row in re.finditer(r'\{"([^"]*)",\s*"((?:[^"\\]|\\.)*)"\}', datums):
        lines.append(f"    ({rust(row.group(1))}, {rust(c_string(chr(34) + row.group(2) + chr(34)))}),")
    lines.append("];")
    open(output, "w", encoding="utf-8").write("\n".join(lines) + "\n")
    return 0


sys.exit(main())
