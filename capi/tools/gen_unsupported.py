#!/usr/bin/env python3
"""Write src/unsupported.rs: one exported function for each proj.h function not yet implemented.

usage: gen_unsupported.py SIGNATURES.rs SRC_DIR OUTPUT

SIGNATURES.rs is the bindgen output of proj.h restricted to functions (`--allowlist-function
'proj_.*'`), run through rustfmt. A function implemented in SRC_DIR (an `extern "C" fn` of the
same name outside OUTPUT) is not repeated. Each remaining function returns what PROJ returns
for a failure (`NULL`, 0) and sets `PROJ_ERR_OTHER_API_MISUSE` on its context, through
`unsupported`: it never returns a result.
"""
import os
import re
import sys


ENUM_FAILURE = {
    "PJ_TYPE": "PJ_TYPE_UNKNOWN",
    "PJ_COORDINATE_SYSTEM_TYPE": "PJ_CS_TYPE_UNKNOWN",
    "PJ_GUESSED_WKT_DIALECT": "PJ_GUESSED_NOT_WKT",
}


def implemented(src_dir: str, output: str) -> set[str]:
    names = set()
    for entry in os.listdir(src_dir):
        path = os.path.join(src_dir, entry)
        if not entry.endswith(".rs") or os.path.abspath(path) == os.path.abspath(output):
            continue
        text = open(path, encoding="utf-8").read()
        names |= set(re.findall(r'pub extern "C" fn (\w+)', text))
    return names


def main() -> int:
    signatures, src_dir, output = sys.argv[1:4]
    text = open(signatures, encoding="utf-8").read()
    done = implemented(src_dir, output)
    pattern = re.compile(r"pub fn (\w+)\(")
    out = [
        "//! Functions of `proj.h` that this port does not implement yet.",
        "//!",
        "//! Generated by `capi/tools/gen_unsupported.py`. Each one fails as PROJ fails (`NULL` or 0)",
        "//! and sets `PROJ_ERR_OTHER_API_MISUSE` with a message naming the function.",
        "",
        "use std::ffi::{c_char, c_int, c_void};",
        "",
        "use crate::context::unsupported;",
        "use crate::ffi::*;",
        "use crate::util::guard;",
        "",
    ]
    count = 0
    for match in pattern.finditer(text):
        name = match.group(1)
        depth, end = 1, match.end()
        while depth:
            depth += {"(": 1, ")": -1}.get(text[end], 0)
            end += 1
        args = " ".join(text[match.end() : end - 1].split()).rstrip(",")
        tail = text[end : text.index(";", end)].strip()
        ret = tail[2:].strip() if tail.startswith("->") else None
        if name in done or not name.startswith("proj_"):
            continue
        ret = " ".join(ret.split()) if ret else None
        if ret is None:
            default = "()"
        elif ret.startswith("*"):
            default = "std::ptr::null_mut()" if ret.startswith("*mut") else "std::ptr::null()"
        elif ret == "PROJ_STRING_LIST":
            default = "std::ptr::null_mut()"
        elif ret in ENUM_FAILURE:
            default = ENUM_FAILURE[ret]
        elif ret in ("f64",):
            default = "0.0"
        elif ret in ("::core::ffi::c_int", "::core::ffi::c_uint", "usize", "::core::ffi::c_long"):
            default = "0"
        else:
            raise SystemExit(f"{name}: return type {ret} has no failure value")
        first = re.match(r"\s*(\w+):\s*\*mut PJ_CONTEXT", args)
        context = first.group(1) if first else "std::ptr::null_mut()"
        params = args.replace("::core::ffi::", "")
        params = re.sub(r"(?<![:\w])(\w+):(?!:)", r"_\1:", params)
        if first:
            params = params.replace(f"_{context}:", f"{context}:", 1)
        ret_text = f" -> {ret.replace('::core::ffi::', '')}" if ret else ""
        out += [
            "#[unsafe(no_mangle)]",
            f'pub extern "C" fn {name}({params}){ret_text} {{',
            f"    guard({default}, || {{",
            f'        unsupported({context}, "{name}");',
            *([] if default == "()" else [f"        {default}"]),
            "    })",
            "}",
            "",
        ]
        count += 1
    text = "\n".join(out)
    used = [name for name in ("c_char", "c_int", "c_void") if name in text.split("use crate::util::guard;", 1)[1]]
    text = text.replace("use std::ffi::{c_char, c_int, c_void};", "use std::ffi::{%s};" % ", ".join(used))
    open(output, "w", encoding="utf-8").write(text)
    print(f"{count} functions", file=sys.stderr)
    return 0


sys.exit(main())
