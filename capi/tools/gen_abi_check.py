#!/usr/bin/env python3
"""Write tests/abi_layout.c from the layout assertions of src/ffi.rs.

usage: gen_abi_check.py FFI.rs OUTPUT.c

ffi.rs asserts at compile time the size, the alignment and the offset of every field of every
structure of proj.h (numbers clang computed on the header). This program states the same
numbers in C, so that a C compiler checks them against a header: `run.sh` compiles the result
against capi/include and against the header of PROJ 9.9.0. Rust and C then agree on every
structure, through the same numbers.
"""
import re
import sys


ALIASES = {"P5_FACTORS": "PJ_FACTORS", "PJ_LIST": "struct PJ_LIST", "PJ_ELLPS": "struct PJ_ELLPS", "PJ_UNITS": "struct PJ_UNITS", "PJ_PRIME_MERIDIANS": "struct PJ_PRIME_MERIDIANS"}


def alias(name: str) -> str:
    return ALIASES.get(name, name)


def main() -> int:
    source = open(sys.argv[1], encoding="utf-8").read()
    lines = [
        "/* Generated by capi/tools/gen_abi_check.py from capi/src/ffi.rs: do not edit. */",
        '#include <stddef.h>',
        '#include "proj.h"',
        "",
        "#define STATIC_ASSERT(condition, message) typedef char message[(condition) ? 1 : -1]",
        "",
    ]
    for match in re.finditer(r'\["Size of (\w+)"\]\[[^\]]*?- (\d+)usize\]', source):
        name, size = match.groups()
        lines.append(f"STATIC_ASSERT(sizeof({alias(name)}) == {size}, size_of_{name});")
    for match in re.finditer(r'\["Alignment of (\w+)"\]\[[^\]]*?- (\d+)usize\]', source):
        name, align = match.groups()
        lines.append(f"STATIC_ASSERT(_Alignof({alias(name)}) == {align}, align_of_{name});")
    for match in re.finditer(
        r'\["Offset of field: (\w+)::(\w+)"\]\s*\[::core::mem::offset_of!\(\w+, (\w+)\) - (\d+)usize\]',
        source,
    ):
        name, _, field, offset = match.groups()
        field = field.removesuffix("_")  # `type_` is Rust's spelling of `type`
        lines.append(
            f"STATIC_ASSERT(offsetof({alias(name)}, {field}) == {offset}, offset_{name}_{field});"
        )
    lines += ["", "int main(void) { return 0; }", ""]
    open(sys.argv[2], "w", encoding="utf-8").write("\n".join(lines))
    return 0


sys.exit(main())
