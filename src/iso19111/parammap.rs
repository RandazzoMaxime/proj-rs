/// First method whose EPSG code is `code`.
#[must_use]
pub(crate) fn method_by_code(code: i32) -> Option<&'static MethodMap> {
    if code == 0 {
        return None;
    }
    PROJECTION_METHODS
        .iter()
        .chain(OTHER_METHODS)
        .find(|method| method.epsg_code == code)
}

/// First method whose WKT2 name matches `name`, ignoring case and separators.
#[must_use]
pub(crate) fn method_by_name(name: &str) -> Option<&'static MethodMap> {
    let wanted = canonical_name(name);
    PROJECTION_METHODS
        .iter()
        .chain(OTHER_METHODS)
        .find(|method| canonical_name(method.wkt2_name) == wanted)
}

fn canonical_name(name: &str) -> String {
    name.chars()
        .filter(|ch| !matches!(ch, ' ' | '_' | '-' | '/' | '{' | '}'))
        .flat_map(|ch| ch.to_lowercase())
        .collect()
}
