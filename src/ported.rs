/// A PROJ string that builds `name`.
#[must_use]
pub fn bench_definition(name: &str) -> String {
    match name {
        "utm" => "+proj=utm +zone=31 +ellps=WGS84".to_owned(),
        "helmert" => "+proj=helmert +x=1 +y=2 +z=3".to_owned(),
        "cart" | "geocent" => format!("+proj={name} +ellps=WGS84"),
        "longlat" | "latlong" | "latlon" | "lonlat" => format!("+proj={name} +ellps=WGS84"),
        "aea" | "leac" | "eqdc" => format!("+proj={name} +lat_1=29 +lat_2=45 +ellps=WGS84"),
        "bonne" => "+proj=bonne +lat_1=45 +ellps=WGS84".to_owned(),
        "euler" | "murd1" | "murd2" | "murd3" | "pconic" | "tissot" | "vitk1" => {
            format!("+proj={name} +lat_1=30 +lat_2=45")
        }
        "oea" => "+proj=oea +n=1 +m=1".to_owned(),
        "lcc" => "+proj=lcc +lat_0=46.5 +lat_1=49 +lat_2=44 +lon_0=3 +ellps=GRS80".to_owned(),
        "ccon" => "+proj=ccon +lat_1=45 +ellps=WGS84".to_owned(),
        "imw_p" => "+proj=imw_p +lat_1=30 +lat_2=50 +ellps=WGS84".to_owned(),
        "labrd" | "lcca" => format!("+proj={name} +lat_0=45 +lon_0=3 +ellps=WGS84"),
        "axisswap" => "+proj=axisswap +order=2,1".to_owned(),
        "ob_tran" => "+proj=ob_tran +o_proj=moll +o_lat_p=45 +o_lon_p=0".to_owned(),
        "topocentric" => "+proj=topocentric +lat_0=48 +lon_0=2 +ellps=WGS84".to_owned(),
        "nsper" => "+proj=nsper +h=500000 +ellps=WGS84".to_owned(),
        "tpers" => "+proj=tpers +h=500000 +tilt=10 +azi=20 +ellps=WGS84".to_owned(),
        "geos" => "+proj=geos +h=35785831 +ellps=WGS84".to_owned(),
        "chamb" => {
            "+proj=chamb +lat_1=40 +lon_1=10 +lat_2=50 +lon_2=20 +lat_3=40 +lon_3=30 +ellps=WGS84"
                .to_owned()
        }
        "som" => "+proj=som +inc_angle=98.2 +asc_lon=-10 +ellps=WGS84".to_owned(),
        "lsat" => "+proj=lsat +lsat=5 +path=10 +ellps=WGS84".to_owned(),
        "misrsom" => "+proj=misrsom +path=1 +ellps=WGS84".to_owned(),
        "rhealpix" => "+proj=rhealpix +north_square=1 +south_square=2".to_owned(),
        "urm5" => "+proj=urm5 +n=1 +q=1 +alpha=0".to_owned(),
        "gn_sinu" => "+proj=gn_sinu +m=1 +n=2".to_owned(),
        "urmfps" => "+proj=urmfps +n=0.5".to_owned(),
        "wink2" | "wintri" => format!("+proj={name} +lat_1=40"),
        "loxim" | "collg" => format!("+proj={name} +lat_1=40 +lat_2=50"),
        "omerc" => "+proj=omerc +lat_0=45 +lonc=10 +alpha=20 +ellps=WGS84".to_owned(),
        "ocea" => "+proj=ocea +lat_1=40 +lon_1=-20 +lat_2=50 +lon_2=20".to_owned(),
        "tpeqd" => "+proj=tpeqd +lat_1=40 +lon_1=-20 +lat_2=50 +lon_2=20".to_owned(),
        "krovak" | "mod_krovak" => format!("+proj={name} +ellps=bessel"),
        "gstmerc" | "somerc" => format!("+proj={name} +lat_0=46.95 +lon_0=7.44 +ellps=bessel"),
        "ups" => "+proj=ups +ellps=WGS84".to_owned(),
        "stere" => "+proj=stere +lat_ts=90 +lat_0=90 +ellps=WGS84".to_owned(),
        "calcofi" | "s2" | "nzmg" => format!("+proj={name}"),
        _ => format!("+proj={name} +ellps=WGS84"),
    }
}
