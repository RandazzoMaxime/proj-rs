#[derive(Clone, Copy)]
struct Xyz {
    x: f64,
    y: f64,
    z: f64,
}

#[derive(Clone, Copy)]
struct Face {
    p1: Xyz,
    p2: Xyz,
    p3: Xyz,
}

type Mat4 = [[f64; 4]; 4];

fn dot(a: Xyz, b: Xyz) -> f64 {
    a.x * b.x + a.y * b.y + a.z * b.z
}

fn det(u: Xyz, v: Xyz, w: Xyz) -> f64 {
    u.x * (v.y * w.z - v.z * w.y) - v.x * (u.y * w.z - u.z * w.y) + w.x * (u.y * v.z - u.z * v.y)
}

fn in_face(point: Xyz, face: Face) -> bool {
    det(point, face.p2, face.p3) <= 0.0
        && det(face.p1, point, face.p3) <= 0.0
        && det(face.p1, face.p2, point) <= 0.0
}

fn mat_mul(left: Mat4, right: Mat4) -> Mat4 {
    let mut out = [[0.0; 4]; 4];
    for i in 0..4 {
        for j in 0..4 {
            out[i][j] = left[i][0] * right[0][j]
                + left[i][1] * right[1][j]
                + left[i][2] * right[2][j]
                + left[i][3] * right[3][j];
        }
    }
    out
}

fn apply(m: Mat4, v: Xyz) -> Xyz {
    Xyz {
        x: m[0][0] * v.x + m[0][1] * v.y + m[0][2] * v.z + m[0][3],
        y: m[1][0] * v.x + m[1][1] * v.y + m[1][2] * v.z + m[1][3],
        z: m[2][0] * v.x + m[2][1] * v.y + m[2][2] * v.z + m[2][3],
    }
}

