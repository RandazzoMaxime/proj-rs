//! Airocean / Fuller icosahedral map, PROJ 9.9 \irocean.cpp\.
//!
//! The projected coordinates are in units of the semi-major axis. The classic
//! wrapper multiplies by \\. An ellipsoid is reduced to the geocentric
//! latitude before the spherical net, and restored on the inverse.

