//! PROJ 9.9.0 `test/unit/test_io.cpp`, WKT parsing of a concatenated operation whose
//! `COORDINATEOPERATION` step uses `METHOD["CTABLE2"]` with a `PARAMETERFILE`.
//!
//! Expected text is copied from PROJ 9.9.0.

use proj_rs::{ProjLines, WktConvention, WktFormatter, WktObject, WktParser};

/// `TEST(wkt_parse, CONCATENATEDOPERATION_with_conversion_coordinateoperation_conversion)`
#[test]
fn wkt_parse_concatenatedoperation_with_conversion_coordinateoperation_conversion() {
    let wkt = concat!(
        "CONCATENATEDOPERATION[\"Inverse of UTM zone 11N + NAD27 to WGS 84 ",
        "(79) + UTM zone 11N\",\n",
        "    VERSION[\"my version\"],\n",
        "    SOURCECRS[\n",
        "        PROJCRS[\"NAD27 / UTM zone 11N\",\n",
        "            BASEGEOGCRS[\"NAD27\",\n",
        "                DATUM[\"North American Datum 1927\",\n",
        "                    ELLIPSOID[\"Clarke ",
        "1866\",6378206.4,294.978698213898,\n",
        "                        LENGTHUNIT[\"metre\",1]]],\n",
        "                PRIMEM[\"Greenwich\",0,\n",
        "                    ANGLEUNIT[\"degree\",0.0174532925199433]]],\n",
        "            CONVERSION[\"UTM zone 11N\",\n",
        "                METHOD[\"Transverse Mercator\",\n",
        "                    ID[\"EPSG\",9807]],\n",
        "                PARAMETER[\"Latitude of natural origin\",0,\n",
        "                    ANGLEUNIT[\"degree\",0.0174532925199433],\n",
        "                    ID[\"EPSG\",8801]],\n",
        "                PARAMETER[\"Longitude of natural origin\",-117,\n",
        "                    ANGLEUNIT[\"degree\",0.0174532925199433],\n",
        "                    ID[\"EPSG\",8802]],\n",
        "                PARAMETER[\"Scale factor at natural origin\",0.9996,\n",
        "                    SCALEUNIT[\"unity\",1],\n",
        "                    ID[\"EPSG\",8805]],\n",
        "                PARAMETER[\"False easting\",500000,\n",
        "                    LENGTHUNIT[\"metre\",1],\n",
        "                    ID[\"EPSG\",8806]],\n",
        "                PARAMETER[\"False northing\",0,\n",
        "                    LENGTHUNIT[\"metre\",1],\n",
        "                    ID[\"EPSG\",8807]]],\n",
        "            CS[Cartesian,2],\n",
        "                AXIS[\"(E)\",east,\n",
        "                    ORDER[1],\n",
        "                    LENGTHUNIT[\"metre\",1]],\n",
        "                AXIS[\"(N)\",north,\n",
        "                    ORDER[2],\n",
        "                    LENGTHUNIT[\"metre\",1]],\n",
        "            ID[\"EPSG\",26711]]],\n",
        "    TARGETCRS[\n",
        "        PROJCRS[\"WGS 84 / UTM zone 11N\",\n",
        "            BASEGEOGCRS[\"WGS 84\",\n",
        "                DATUM[\"World Geodetic System 1984\",\n",
        "                    ELLIPSOID[\"WGS 84\",6378137,298.257223563,\n",
        "                        LENGTHUNIT[\"metre\",1]]],\n",
        "                PRIMEM[\"Greenwich\",0,\n",
        "                    ANGLEUNIT[\"degree\",0.0174532925199433]]],\n",
        "            CONVERSION[\"UTM zone 11N\",\n",
        "                METHOD[\"Transverse Mercator\",\n",
        "                    ID[\"EPSG\",9807]],\n",
        "                PARAMETER[\"Latitude of natural origin\",0,\n",
        "                    ANGLEUNIT[\"degree\",0.0174532925199433],\n",
        "                    ID[\"EPSG\",8801]],\n",
        "                PARAMETER[\"Longitude of natural origin\",-117,\n",
        "                    ANGLEUNIT[\"degree\",0.0174532925199433],\n",
        "                    ID[\"EPSG\",8802]],\n",
        "                PARAMETER[\"Scale factor at natural origin\",0.9996,\n",
        "                    SCALEUNIT[\"unity\",1],\n",
        "                    ID[\"EPSG\",8805]],\n",
        "                PARAMETER[\"False easting\",500000,\n",
        "                    LENGTHUNIT[\"metre\",1],\n",
        "                    ID[\"EPSG\",8806]],\n",
        "                PARAMETER[\"False northing\",0,\n",
        "                    LENGTHUNIT[\"metre\",1],\n",
        "                    ID[\"EPSG\",8807]]],\n",
        "            CS[Cartesian,2],\n",
        "                AXIS[\"(E)\",east,\n",
        "                    ORDER[1],\n",
        "                    LENGTHUNIT[\"metre\",1]],\n",
        "                AXIS[\"(N)\",north,\n",
        "                    ORDER[2],\n",
        "                    LENGTHUNIT[\"metre\",1]],\n",
        "            ID[\"EPSG\",32611]]],\n",
        "    STEP[\n",
        "        CONVERSION[\"Inverse of UTM zone 11N\",\n",
        "            METHOD[\"Inverse of Transverse Mercator\",\n",
        "                ID[\"INVERSE(EPSG)\",9807]],\n",
        "            PARAMETER[\"Latitude of natural origin\",0,\n",
        "                ANGLEUNIT[\"degree\",0.0174532925199433],\n",
        "                ID[\"EPSG\",8801]],\n",
        "            PARAMETER[\"Longitude of natural origin\",-117,\n",
        "                ANGLEUNIT[\"degree\",0.0174532925199433],\n",
        "                ID[\"EPSG\",8802]],\n",
        "            PARAMETER[\"Scale factor at natural origin\",0.9996,\n",
        "                SCALEUNIT[\"unity\",1],\n",
        "                ID[\"EPSG\",8805]],\n",
        "            PARAMETER[\"False easting\",500000,\n",
        "                LENGTHUNIT[\"metre\",1],\n",
        "                ID[\"EPSG\",8806]],\n",
        "            PARAMETER[\"False northing\",0,\n",
        "                LENGTHUNIT[\"metre\",1],\n",
        "                ID[\"EPSG\",8807]],\n",
        "            ID[\"INVERSE(EPSG)\",16011]]],\n",
        "    STEP[\n",
        "        COORDINATEOPERATION[\"NAD27 to WGS 84 (79)\",\n",
        "            SOURCECRS[\n",
        "                GEOGCRS[\"NAD27\",\n",
        "                    DATUM[\"North American Datum 1927\",\n",
        "                        ELLIPSOID[\"Clarke ",
        "1866\",6378206.4,294.978698213898,\n",
        "                            LENGTHUNIT[\"metre\",1]]],\n",
        "                    PRIMEM[\"Greenwich\",0,\n",
        "                        ANGLEUNIT[\"degree\",0.0174532925199433]],\n",
        "                    CS[ellipsoidal,2],\n",
        "                        AXIS[\"geodetic latitude (Lat)\",north,\n",
        "                            ORDER[1],\n",
        "                            ",
        "ANGLEUNIT[\"degree\",0.0174532925199433]],\n",
        "                        AXIS[\"geodetic longitude (Lon)\",east,\n",
        "                            ORDER[2],\n",
        "                            ",
        "ANGLEUNIT[\"degree\",0.0174532925199433]]]],\n",
        "            TARGETCRS[\n",
        "                GEOGCRS[\"WGS 84\",\n",
        "                    DATUM[\"World Geodetic System 1984\",\n",
        "                        ELLIPSOID[\"WGS 84\",6378137,298.257223563,\n",
        "                            LENGTHUNIT[\"metre\",1]]],\n",
        "                    PRIMEM[\"Greenwich\",0,\n",
        "                        ANGLEUNIT[\"degree\",0.0174532925199433]],\n",
        "                    CS[ellipsoidal,2],\n",
        "                        AXIS[\"geodetic latitude (Lat)\",north,\n",
        "                            ORDER[1],\n",
        "                            ",
        "ANGLEUNIT[\"degree\",0.0174532925199433]],\n",
        "                        AXIS[\"geodetic longitude (Lon)\",east,\n",
        "                            ORDER[2],\n",
        "                            ",
        "ANGLEUNIT[\"degree\",0.0174532925199433]]]],\n",
        "            METHOD[\"CTABLE2\"],\n",
        "            PARAMETERFILE[\"Latitude and longitude difference ",
        "file\",\"conus\"],\n",
        "            ID[\"DERIVED_FROM(EPSG)\",15851]]],\n",
        "    STEP[\n",
        "        CONVERSION[\"UTM zone 11N\",\n",
        "            METHOD[\"Transverse Mercator\",\n",
        "                ID[\"EPSG\",9807]],\n",
        "            PARAMETER[\"Latitude of natural origin\",0,\n",
        "                ANGLEUNIT[\"degree\",0.0174532925199433],\n",
        "                ID[\"EPSG\",8801]],\n",
        "            PARAMETER[\"Longitude of natural origin\",-117,\n",
        "                ANGLEUNIT[\"degree\",0.0174532925199433],\n",
        "                ID[\"EPSG\",8802]],\n",
        "            PARAMETER[\"Scale factor at natural origin\",0.9996,\n",
        "                SCALEUNIT[\"unity\",1],\n",
        "                ID[\"EPSG\",8805]],\n",
        "            PARAMETER[\"False easting\",500000,\n",
        "                LENGTHUNIT[\"metre\",1],\n",
        "                ID[\"EPSG\",8806]],\n",
        "            PARAMETER[\"False northing\",0,\n",
        "                LENGTHUNIT[\"metre\",1],\n",
        "                ID[\"EPSG\",8807]],\n",
        "            ID[\"EPSG\",16011]]]]",
    );
    let WktObject::Concatenated(concat) = WktParser::new().create_from_wkt(wkt).expect("wkt")
    else {
        panic!("not a concatenated operation");
    };
    assert_eq!(concat.version(), Some("my version"));
    assert_eq!(
        concat
            .export_to_proj_string(ProjLines::Single)
            .expect("PROJ string"),
        "+proj=pipeline +step +inv +proj=utm +zone=11 +ellps=clrk66 \
         +step +proj=hgridshift +grids=conus +step +proj=utm \
         +zone=11 +ellps=WGS84"
    );
    let out = concat
        .export_to_wkt(&mut WktFormatter::create(WktConvention::Wkt2_2019))
        .expect("WKT");
    assert_eq!(out, wkt);
}
