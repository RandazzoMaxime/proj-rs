//! PROJ 9.9.0 `test/unit/test_io.cpp`, WKT parsing of a concatenated operation whose
//! source is a compound CRS and whose middle step is a PROJ-based operation.

use proj_rs::{ProjLines, WktObject, WktParser};

/// `TEST(wkt_parse, CONCATENATEDOPERATION_with_inverse_conversion_of_compound)`
#[test]
fn wkt_parse_concatenatedoperation_with_inverse_conversion_of_compound() {
    let wkt = r#"CONCATENATEDOPERATION["Inverse of RD New + Amersfoort to ETRS89 (9) + Inverse of ETRS89 to NAP height (2) + ETRS89 to WGS 84 (1)",
    SOURCECRS[
        COMPOUNDCRS["Amersfoort / RD New + NAP height",
            PROJCRS["Amersfoort / RD New",
                BASEGEOGCRS["Amersfoort",
                    DATUM["Amersfoort",
                        ELLIPSOID["Bessel 1841",6377397.155,299.1528128,
                            LENGTHUNIT["metre",1]]],
                    PRIMEM["Greenwich",0,
                        ANGLEUNIT["degree",0.0174532925199433]],
                    ID["EPSG",4289]],
                CONVERSION["RD New",
                    METHOD["Oblique Stereographic",
                        ID["EPSG",9809]],
                    PARAMETER["Latitude of natural origin",52.1561605555556,
                        ANGLEUNIT["degree",0.0174532925199433],
                        ID["EPSG",8801]],
                    PARAMETER["Longitude of natural origin",5.38763888888889,
                        ANGLEUNIT["degree",0.0174532925199433],
                        ID["EPSG",8802]],
                    PARAMETER["Scale factor at natural origin",0.9999079,
                        SCALEUNIT["unity",1],
                        ID["EPSG",8805]],
                    PARAMETER["False easting",155000,
                        LENGTHUNIT["metre",1],
                        ID["EPSG",8806]],
                    PARAMETER["False northing",463000,
                        LENGTHUNIT["metre",1],
                        ID["EPSG",8807]]],
                CS[Cartesian,2],
                    AXIS["easting (X)",east,
                        ORDER[1],
                        LENGTHUNIT["metre",1]],
                    AXIS["northing (Y)",north,
                        ORDER[2],
                        LENGTHUNIT["metre",1]]],
            VERTCRS["NAP height",
                VDATUM["Normaal Amsterdams Peil"],
                CS[vertical,1],
                    AXIS["gravity-related height (H)",up,
                        LENGTHUNIT["metre",1]]],
            ID["EPSG",7415]]],
    TARGETCRS[
        GEOGCRS["WGS 84 (3D)",
            ENSEMBLE["World Geodetic System 1984 ensemble",
                MEMBER["World Geodetic System 1984 (Transit)"],
                MEMBER["World Geodetic System 1984 (G730)"],
                MEMBER["World Geodetic System 1984 (G873)"],
                MEMBER["World Geodetic System 1984 (G1150)"],
                MEMBER["World Geodetic System 1984 (G1674)"],
                MEMBER["World Geodetic System 1984 (G1762)"],
                MEMBER["World Geodetic System 1984 (G2139)"],
                ELLIPSOID["WGS 84",6378137,298.257223563,
                    LENGTHUNIT["metre",1]],
                ENSEMBLEACCURACY[2.0]],
            PRIMEM["Greenwich",0,
                ANGLEUNIT["degree",0.0174532925199433]],
            CS[ellipsoidal,3],
                AXIS["geodetic latitude (Lat)",north,
                    ORDER[1],
                    ANGLEUNIT["degree minute second hemisphere",0.0174532925199433]],
                AXIS["geodetic longitude (Long)",east,
                    ORDER[2],
                    ANGLEUNIT["degree minute second hemisphere",0.0174532925199433]],
                AXIS["ellipsoidal height (h)",up,
                    ORDER[3],
                    LENGTHUNIT["metre",1]],
            ID["EPSG",4329]]],
    STEP[
        CONVERSION["Inverse of RD New",
            METHOD["Inverse of Oblique Stereographic",
                ID["INVERSE(EPSG)",9809]],
            PARAMETER["Latitude of natural origin",52.1561605555556,
                ANGLEUNIT["degree",0.0174532925199433],
                ID["EPSG",8801]],
            PARAMETER["Longitude of natural origin",5.38763888888889,
                ANGLEUNIT["degree",0.0174532925199433],
                ID["EPSG",8802]],
            PARAMETER["Scale factor at natural origin",0.9999079,
                SCALEUNIT["unity",1],
                ID["EPSG",8805]],
            PARAMETER["False easting",155000,
                LENGTHUNIT["metre",1],
                ID["EPSG",8806]],
            PARAMETER["False northing",463000,
                LENGTHUNIT["metre",1],
                ID["EPSG",8807]],
            ID["INVERSE(EPSG)",19914]]],
    STEP[
        COORDINATEOPERATION["PROJ-based coordinate operation",
            SOURCECRS[
                COMPOUNDCRS["Amersfoort + NAP height",
                    GEOGCRS["Amersfoort",
                        DATUM["Amersfoort",
                            ELLIPSOID["Bessel 1841",6377397.155,299.1528128,
                                LENGTHUNIT["metre",1]]],
                        PRIMEM["Greenwich",0,
                            ANGLEUNIT["degree",0.0174532925199433]],
                        CS[ellipsoidal,2],
                            AXIS["geodetic latitude (Lat)",north,
                                ORDER[1],
                                ANGLEUNIT["degree",0.0174532925199433]],
                            AXIS["geodetic longitude (Lon)",east,
                                ORDER[2],
                                ANGLEUNIT["degree",0.0174532925199433]],
                        ID["EPSG",4289]],
                    VERTCRS["NAP height",
                        VDATUM["Normaal Amsterdams Peil"],
                        CS[vertical,1],
                            AXIS["gravity-related height (H)",up,
                                LENGTHUNIT["metre",1]],
                        ID["EPSG",5709]]]],
            TARGETCRS[
                GEOGCRS["WGS 84 (3D)",
                    ENSEMBLE["World Geodetic System 1984 ensemble",
                        MEMBER["World Geodetic System 1984 (Transit)"],
                        MEMBER["World Geodetic System 1984 (G730)"],
                        MEMBER["World Geodetic System 1984 (G873)"],
                        MEMBER["World Geodetic System 1984 (G1150)"],
                        MEMBER["World Geodetic System 1984 (G1674)"],
                        MEMBER["World Geodetic System 1984 (G1762)"],
                        MEMBER["World Geodetic System 1984 (G2139)"],
                        ELLIPSOID["WGS 84",6378137,298.257223563,
                            LENGTHUNIT["metre",1]],
                        ENSEMBLEACCURACY[2.0]],
                    PRIMEM["Greenwich",0,
                        ANGLEUNIT["degree",0.0174532925199433]],
                    CS[ellipsoidal,3],
                        AXIS["geodetic latitude (Lat)",north,
                            ORDER[1],
                            ANGLEUNIT["degree minute second hemisphere",0.0174532925199433]],
                        AXIS["geodetic longitude (Long)",east,
                            ORDER[2],
                            ANGLEUNIT["degree minute second hemisphere",0.0174532925199433]],
                        AXIS["ellipsoidal height (h)",up,
                            ORDER[3],
                            LENGTHUNIT["metre",1]],
                    ID["EPSG",4329]]],
            METHOD["PROJ-based operation method: +proj=pipeline +step +proj=axisswap +order=2,1 +step +proj=unitconvert +xy_in=deg +xy_out=rad +step +proj=hgridshift +grids=nl_nsgi_rdtrans2018.tif +step +proj=vgridshift +grids=nl_nsgi_nlgeo2018.tif +multiplier=1 +step +proj=unitconvert +xy_in=rad +xy_out=deg +step +proj=axisswap +order=2,1"],
            OPERATIONACCURACY[1.002]]],
    USAGE[
        SCOPE["unknown"],
        AREA["Netherlands - onshore, including Waddenzee, Dutch Wadden Islands and 12-mile offshore coastal zone."],
        BBOX[50.75,3.2,53.7,7.22]]]"#;
    let object = WktParser::new().create_from_wkt(wkt).expect("wkt");
    let WktObject::Concatenated(concat) = object else {
        panic!("expected a concatenated operation");
    };
    let actual = concat
        .export_to_proj_string(ProjLines::Single)
        .expect("PROJ string");
    let expected = "+proj=pipeline +step +inv +proj=sterea +lat_0=52.1561605555556 +lon_0=5.38763888888889 +k=0.9999079 +x_0=155000 +y_0=463000 +ellps=bessel +step +proj=hgridshift +grids=nl_nsgi_rdtrans2018.tif +step +proj=vgridshift +grids=nl_nsgi_nlgeo2018.tif +multiplier=1 +step +proj=unitconvert +xy_in=rad +xy_out=deg +step +proj=axisswap +order=2,1";
    assert_eq!(actual, expected);
}
